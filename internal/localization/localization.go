// Package localization holds the reference lists apps offer choices from:
// languages, countries and parental ratings.
package localization

import (
	_ "embed"
	"encoding/json"
	"slices"
	"strings"
	"sync"

	"golang.org/x/text/language"
	"golang.org/x/text/language/display"
)

// Language is an ISO 639-2 language.
type Language struct {
	// Name is the English name as the standard lists it ("Spanish;
	// Castilian").
	Name string
	// Bibliographic is the ISO 639-2/B code ("fre"), the code of languages
	// that have a single one.
	Bibliographic string
	// Terminology is the ISO 639-2/T code when it differs ("fra").
	Terminology string
	// Alpha2 is the ISO 639-1 code, for the languages that have one ("fr").
	Alpha2 string
}

// languagesJSON is generated by scripts/localization-data.sh from the
// Library of Congress's ISO 639-2 list.
//
//go:embed languages.json
var languagesJSON []byte

var languages = sync.OnceValue(func() []Language {
	var list []Language
	if err := json.Unmarshal(languagesJSON, &list); err != nil {
		panic("localization: embedded languages: " + err.Error())
	}
	return list
})

// codes maps every code of a language, in lower case, to its bibliographic
// code: "fre", "fra" and "fr" all give "fre".
var codes = sync.OnceValue(func() map[string]string {
	all := languages()
	index := make(map[string]string, 2*len(all))
	for _, language := range all {
		for _, code := range [...]string{language.Bibliographic, language.Terminology, language.Alpha2} {
			if code != "" {
				index[code] = language.Bibliographic
			}
		}
	}
	return index
})

// Languages returns the ISO 639-2 languages, sorted by English name. The
// list is shared: callers must not change it.
func Languages() []Language {
	return languages()
}

// Countries returns the ISO 3166-1 countries, sorted by English name. The
// list is shared: callers must not change it.
func Countries() []Country {
	return countries()
}

// LanguageCode returns the ISO 639-2/B code of a language given by any of
// its codes, in any letter case: "fra", "FRE" and "fr" all give "fre".
// Region subtags are ignored ("fr-CA" gives "fre"), and anything else is
// returned in lower case, so that two unknown tags still compare.
func LanguageCode(code string) string {
	code = strings.ToLower(strings.TrimSpace(code))
	if bibliographic, ok := codes()[code]; ok {
		return bibliographic
	}
	if base, _, cut := strings.Cut(strings.ReplaceAll(code, "_", "-"), "-"); cut {
		if bibliographic, ok := codes()[base]; ok {
			return bibliographic
		}
	}
	return code
}

// SameLanguage reports whether two codes name the same language, whichever
// of its ISO 639 codes each uses. An empty code matches nothing.
func SameLanguage(a, b string) bool {
	a, b = LanguageCode(a), LanguageCode(b)
	return a != "" && a == b
}

// KnownLanguage reports whether code is one of an ISO 639 language's codes,
// in any letter case.
func KnownLanguage(code string) bool {
	_, ok := codes()[strings.ToLower(strings.TrimSpace(code))]
	return ok
}

// LanguageTag returns the shortest code of a language given by any of its
// codes, as browsers name languages: its ISO 639-1 code ("fre" gives
// "fr"), else its ISO 639-2/T code, else its only one. An unknown code is
// returned in lower case.
func LanguageTag(code string) string {
	bibliographic := LanguageCode(code)
	for _, l := range languages() {
		if l.Bibliographic == bibliographic {
			if l.Alpha2 != "" {
				return l.Alpha2
			}
			if l.Terminology != "" {
				return l.Terminology
			}
			return l.Bibliographic
		}
	}
	return bibliographic
}

// names maps the names of the languages that have an ISO 639-1 code, in
// lower case, to their bibliographic code: their English names as the
// standard lists them ("Spanish; Castilian" gives both), and as the
// Unicode CLDR names them in English, in French and in the language
// itself ("français").
var names = sync.OnceValue(func() map[string]string {
	index := map[string]string{}
	add := func(name, code string) {
		if name = strings.ToLower(strings.TrimSpace(name)); name != "" {
			if _, taken := index[name]; !taken {
				index[name] = code
			}
		}
	}
	english, french := display.English.Languages(), display.French.Languages()
	for _, l := range languages() {
		for name := range strings.SplitSeq(l.Name, ";") {
			add(name, l.Bibliographic)
		}
		if l.Alpha2 == "" {
			continue
		}
		tag := language.Make(l.Alpha2)
		add(english.Name(tag), l.Bibliographic)
		add(french.Name(tag), l.Bibliographic)
		add(display.Self.Name(tag), l.Bibliographic)
	}
	return index
})

// LanguageCodes returns the ISO 639-2/B codes of the languages a text
// names, each once, as addons give a title's language: by code ("fr",
// "fre", "fr-CA") or by name ("French", "Français"), several separated by
// commas, slashes, semicolons or "|". What names no language is left out.
func LanguageCodes(text string) []string {
	var result []string
	for part := range strings.FieldsFuncSeq(text, func(r rune) bool { return r == ',' || r == '/' || r == ';' || r == '|' }) {
		part = strings.ToLower(strings.TrimSpace(part))
		code, ok := names()[part]
		if !ok {
			if code = LanguageCode(part); !KnownLanguage(code) {
				continue
			}
		}
		if !slices.Contains(result, code) {
			result = append(result, code)
		}
	}
	return result
}

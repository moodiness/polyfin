// The data of the languages Tesseract lacks can be downloaded into
// DataDir from Tesseract's own data, the fast models of tessdata_fast,
// at a pinned commit: each file is checked against the size and SHA-256
// listed for it at that commit, built into Polyfin, before it is kept.

// DataCommit is the commit of tesseract-ocr/tessdata_fast the files are
// downloaded at, and DataURL the address they are found under, followed
// by their name. scripts/tessdata-list.sh pins the same commit.
const (
	DataCommit = "87416418657359cb625c412a48b6e1d6d41c29bd"
	DataURL    = "https://raw.githubusercontent.com/tesseract-ocr/tessdata_fast/" + DataCommit + "/"
)

// DataFile is a language's .traineddata file at DataCommit.
type DataFile struct {
	// Language is the language's Tesseract code, the file's name without
	// its extension: "fin", "chi_sim".
	Language string
	Size     int64
	// SHA256 is the file's SHA-256, in lower-case hexadecimal.
	SHA256 string
}

// tessdataJSON is generated by scripts/tessdata-list.sh.
//
//go:embed tessdata.json
var tessdataJSON []byte

// dataFiles are the files of tessdataJSON, by language.
var dataFiles = func() map[string]DataFile {
	var list []DataFile
	if err := json.Unmarshal(tessdataJSON, &list); err != nil {
		panic(err)
	}
	files := make(map[string]DataFile, len(list))
	for _, file := range list {
		files[file.Language] = file
	}
	return files
}()

// Errors of Download, besides *FolderError and *FetchError.
var (
	// ErrUnknownLanguage reports a language with no file at DataCommit.
	ErrUnknownLanguage = errors.New("no Tesseract data to download for the language")
	// ErrNoDataDir reports a download without a folder to keep it in.
	ErrNoDataDir = errors.New("POLYFIN_TESSDATA_DIR is not set")
	// ErrChecksum reports a file whose size or SHA-256 is not that listed
	// for it: it is not kept.
	ErrChecksum = errors.New("the downloaded file's SHA-256 is not that of Tesseract's data")
)

// FolderError reports a folder the data could not be written into.
type FolderError struct {
	Dir string
	Err error
}

func (e *FolderError) Error() string {
	return fmt.Sprintf("the folder %s cannot be written: %v", e.Dir, e.Err)
}

func (e *FolderError) Unwrap() error { return e.Err }

// FetchError reports a file that could not be downloaded.
type FetchError struct {
	URL string
	Err error
}

func (e *FetchError) Error() string {
	return fmt.Sprintf("download %s: %v", e.URL, e.Err)
}

func (e *FetchError) Unwrap() error { return e.Err }

// downloadTime bounds a download: the largest file is about 12 MB.
const downloadTime = 10 * time.Minute

// Downloader downloads the data of languages into Dir.
type Downloader struct {
	// Dir is the folder the files are kept in, Tesseract.DataDir; empty
	// for none, which downloads nothing.
	Dir string
	// URL is the address the files are found under, followed by their
	// name; DataURL when empty.
	URL string
	// Client makes the requests; one with the default transport, which
	// goes through the proxy the environment sets, when nil.
	Client *http.Client
	// Files are the files downloaded, by language; those at DataCommit,
	// built into Polyfin, when nil.
	Files map[string]DataFile

	// mu has one download run at a time.
	mu sync.Mutex
}

// Downloadable reports whether Download can fetch the data of language:
// it is listed at DataCommit, and there is a folder to keep it in.
func (d *Downloader) Downloadable(language string) bool {
	_, listed := d.file(language)
	return d != nil && d.Dir != "" && listed
}

// Download fetches the data of language, a Tesseract code, into Dir: it
// creates the folder if missing, writes the file under a temporary name,
// checks its size and SHA-256, and only then renames it into place. A
// file already there with the right SHA-256 is kept as it is.
func (d *Downloader) Download(ctx context.Context, language string) error {
	file, ok := d.file(language)
	if !ok {
		return ErrUnknownLanguage
	}
	if d.Dir == "" {
		return ErrNoDataDir
	}
	d.mu.Lock()
	defer d.mu.Unlock()
	target := filepath.Join(d.Dir, language+".traineddata")
	if sum, err := fileSHA256(target); err == nil && sum == file.SHA256 {
		return nil
	}
	if err := os.MkdirAll(d.Dir, 0o755); err != nil {
		return &FolderError{d.Dir, err}
	}
	// The temporary name does not end in .traineddata, so that Tesseract
	// is never told of a file not checked yet.
	temp, err := os.CreateTemp(d.Dir, "."+language+"-*.download")
	if err != nil {
		return &FolderError{d.Dir, err}
	}
	defer os.Remove(temp.Name())
	defer temp.Close()
	if err := d.fetch(ctx, file, temp); err != nil {
		return err
	}
	if err := temp.Close(); err != nil {
		return &FolderError{d.Dir, err}
	}
	// CreateTemp gives the owner alone access; Tesseract may run as
	// another user.
	if err := os.Chmod(temp.Name(), 0o644); err != nil {
		return &FolderError{d.Dir, err}
	}
	if err := os.Rename(temp.Name(), target); err != nil {
		return &FolderError{d.Dir, err}
	}
	return nil
}

// fetch downloads file into out, checking its size and SHA-256.
func (d *Downloader) fetch(ctx context.Context, file DataFile, out *os.File) error {
	base := d.URL
	if base == "" {
		base = DataURL
	}
	address := strings.TrimSuffix(base, "/") + "/" + file.Language + ".traineddata"
	ctx, cancel := context.WithTimeout(ctx, downloadTime)
	defer cancel()
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, address, nil)
	if err != nil {
		return &FetchError{address, err}
	}
	client := d.Client
	if client == nil {
		client = &http.Client{Transport: http.DefaultTransport.(*http.Transport).Clone()}
	}
	response, err := client.Do(request)
	if err != nil {
		return &FetchError{address, err}
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return &FetchError{address, fmt.Errorf("the server answered %s", response.Status)}
	}
	hash := sha256.New()
	// One byte more than listed tells a file too long.
	written, err := io.Copy(io.MultiWriter(out, hash), io.LimitReader(response.Body, file.Size+1))
	if err != nil {
		var pathErr *os.PathError
		if errors.As(err, &pathErr) {
			return &FolderError{d.Dir, err}
		}
		return &FetchError{address, err}
	}
	if written != file.Size || hex.EncodeToString(hash.Sum(nil)) != file.SHA256 {
		return ErrChecksum
	}
	return nil
}

// file is the file of language.
func (d *Downloader) file(language string) (DataFile, bool) {
	files := dataFiles
	if d != nil && d.Files != nil {
		files = d.Files
	}
	file, ok := files[language]
	return file, ok
}

// fileSHA256 is the SHA-256 of a file, in lower-case hexadecimal.
func fileSHA256(name string) (string, error) {
	f, err := os.Open(name)
	if err != nil {
		return "", err
	}
	defer f.Close()
	hash := sha256.New()
	if _, err := io.Copy(hash, f); err != nil {
		return "", err
	}
	return hex.EncodeToString(hash.Sum(nil)), nil
}
